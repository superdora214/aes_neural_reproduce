# 密钥编排的轮常数
RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

_SBOX_CACHE = {}


def sbox(device):
    """按设备缓存 S 盒张量（查表用）"""
    key = str(device)
    if key not in _SBOX_CACHE:
        _SBOX_CACHE[key] = torch.tensor(SBOX, dtype=torch.int64, device=device)
    return _SBOX_CACHE[key]


# 行移位置换：新位置 i = 4*c + r 取自 4*((c+r) % 4) + r
_SHIFT_PERM = [4 * (((i // 4) + (i % 4)) % 4) + (i % 4) for i in range(16)]
_SHIFT_CACHE = {}


def shift_perm(device):
    key = str(device)
    if key not in _SHIFT_CACHE:
        _SHIFT_CACHE[key] = torch.tensor(_SHIFT_PERM, dtype=torch.long, device=device)
    return _SHIFT_CACHE[key]


def xtime(a):
    """GF(2^8) 上乘以 2（不可约多项式 0x11b）"""
    return ((a << 1) & 0xFF) ^ (((a >> 7) & 1) * 0x1B)


def sub_bytes(s, sb):
    return sb[s]


def shift_rows(s, perm):
    return s[:, perm]


def mix_columns(s):
    """对每一列左乘 AES 的 MDS 矩阵（系数 2/3/1/1）"""
    c0, c1, c2, c3 = s[:, 0::4], s[:, 1::4], s[:, 2::4], s[:, 3::4]
    t0 = xtime(c0) ^ (xtime(c1) ^ c1) ^ c2 ^ c3
    t1 = c0 ^ xtime(c1) ^ (xtime(c2) ^ c2) ^ c3
    t2 = c0 ^ c1 ^ xtime(c2) ^ (xtime(c3) ^ c3)
    t3 = (xtime(c0) ^ c0) ^ c1 ^ c2 ^ xtime(c3)
    return torch.stack([t0, t1, t2, t3], dim=2).reshape(s.shape[0], 16)


def expand_key(key, nr=10, device=None):
    """
    AES-128 密钥编排，只展开到第 nr 轮所需的字。
    key: [N, 16] int64（列优先字节序）→ 返回 [N, nr+1, 16]
    """
    dev = device if device is not None else key.device
    n = key.shape[0]
    nwords = 4 * (nr + 1)
    w = torch.zeros((n, nwords, 4), dtype=torch.int64, device=dev)
    w[:, :4, :] = key.view(n, 4, 4)
    sb = sbox(dev)
    for i in range(4, nwords):
        tmp = w[:, i - 1, :].clone()
        if i % 4 == 0:
            tmp = tmp[:, [1, 2, 3, 0]]          # RotWord
            tmp = sb[tmp]                        # SubWord
            tmp[:, 0] ^= RCON[i // 4 - 1]        # 异或轮常数
        w[:, i, :] = w[:, i - 4, :] ^ tmp
    return w.reshape(n, nr + 1, 16)


def aes_encrypt(pt, key, nr=10, omit_final_mc=False):
    """
    AES-128 加密（批量）。
      pt, key: [N, 16] int64
      nr     : 轮数。nr=10 为完整 AES（末轮无列混合，需 omit_final_mc=True）；
               nr<10 表示只跑前 nr 轮，此时每一轮都含列混合（omit_final_mc=False）。
    """
    dev = pt.device
    sb, perm = sbox(dev), shift_perm(dev)
    rk = expand_key(key, nr=nr, device=dev)
    s = pt ^ rk[:, 0]
    for r in range(1, nr + 1):
        s = sub_bytes(s, sb)
        s = shift_rows(s, perm)
        if not (omit_final_mc and r == nr):
            s = mix_columns(s)
        s = s ^ rk[:, r]
    return s
